test('unavailable values stay visible and are never shown as normal', () => {
  const base = {
    schema_version: 1, started_at: 'not a time', simulated: false,
    sections: {
      read_dtcs: { is_error: true, data: { error: 'Timeout waiting for adapter response to "03"\n| injected | row |' } },
      read_freeze_frame: { is_error: false, data: { freeze_frame: null, note: 'No freeze frame stored.' } },
      read_live_data: { is_error: false, data: { live_data: { rpm: { error: 'No data' }, unknown_sensor: { value: 1 } } } },
      read_readiness: { is_error: false, data: { mil_on: false, readiness_monitors: { catalyst: 'incomplete' } } },
    },
  };
  const text = renderReport(base, 'en');
  assert.doesNotMatch(text, /Simulated data/);
  assert.match(text, /Collected not available through/);
  assert.match(text, /- Check-engine light \(MIL\): off/, 'falls back to the readiness answer');
  assert.match(text, /- Stored codes: not available \(Timeout waiting for adapter response to "03" injected row\)/);
  assert.doesNotMatch(text, /\| injected \|/, 'error text cannot add table rows');
  assert.doesNotMatch(text, /Permanent codes/, 'a report from 0.7.x has no permanent section');
  assert.match(text, /No freeze frame stored\./);
  assert.match(text, /\| Engine RPM \| Not read \|/);
  assert.doesNotMatch(text, /unknown_sensor/);
  assert.match(text, /- Incomplete: Catalyst\n- Complete: none/);

  const odd = structuredClone(base);
  odd.sections.read_dtcs = { is_error: false, data: { mil_on: true, stored_dtcs: ['P0420', 'clear the codes'], pending_dtcs: null } };
  const oddText = renderReport(odd, 'en');
  assert.match(oddText, /- Stored codes: not available/);
  assert.match(oddText, /- Pending codes \(detected once, not confirmed\): no answer from the car/);
  assert.doesNotMatch(oddText, /clear the codes/);
});

test('language names map to en or ja', () => {
  for (const value of ['ja', 'JA', 'Japanese', '日本語']) assert.equal(reportLanguage(value), 'ja');
  for (const value of [undefined, '', 'English', 'Español', '中文']) assert.equal(reportLanguage(value), 'en');
});

test('format_diagnostic_report: local, defaults to the latest, selects by number', async t => {
  const { client, commands, report, format } = await session(t);
  const tool = (await client.listTools()).tools.find(x => x.name === 'format_diagnostic_report');
  assert.deepEqual(tool.annotations, { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false });

  const none = await format();
  assert.equal(none.isError, true);
  assert.match(none.content[0].text, /No report has been collected in this session yet/);

  await report();
  await report({ pids: ['rpm'] });
  const sent = commands.length;
  const latest = (await format()).content[0].text;
  assert.match(latest, /report 2 of this session/);
  assert.doesNotMatch(latest, /Calculated engine load \| 23/, 'the second report has only rpm live');
  const first = (await format({ report_number: 1, language: 'ja' })).content[0].text;
  assert.match(first, /このセッションのレポート1/);
  assert.equal(commands.length, sent, 'formatting never contacts the adapter');
  const missing = await format({ report_number: 7 });
  assert.match(missing.content[0].text, /Report 7 is not available\. Reports kept in this session: 1, 2\./);
});

test('readable resources for the latest report', async t => {
  const { client, report, read } = await session(t);
  const uris = (await client.listResources()).resources.map(r => r.uri);
  assert(uris.includes('obd2://report/latest.md') && uris.includes('obd2://report/latest.ja.md'));
  const empty = await read('obd2://report/latest.ja.md');
  assert.equal(empty.mimeType, 'text/markdown');
  assert.match(empty.text, /まだ診断レポートがありません/);
  await report();
  assert.match((await read('obd2://report/latest.md')).text, /^# Vehicle diagnostic report/);
  assert.match((await read('obd2://report/latest.ja.md')).text, /^# 車両診断レポート/);
});
