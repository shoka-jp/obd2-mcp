import test from 'node:test';
import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { Elm327 } from '../dist/elm327.js';
import { MockTransport } from '../dist/mock.js';
import { buildServer } from '../dist/server.js';
import { renderReport, reportLanguage } from '../dist/report-text.js';
import { VERSION } from '../dist/version.js';

async function session(t, scenario = 'catalyst') {
  const mock = new MockTransport(scenario);
  const commands = [];
  const transport = {
    describe: () => mock.describe(), open: () => mock.open(), close: () => mock.close(),
    sendRaw: async command => { commands.push(command); return mock.sendRaw(command); },
  };
  const server = buildServer(new Elm327(transport), true);
  const client = new Client({ name: 'report-text-test', version: '1' });
  const [a, b] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(b), client.connect(a)]);
  t.after(async () => { await client.close(); await server.close(); });
  const report = async (args = {}) => JSON.parse((await client.callTool({ name: 'read_diagnostic_report', arguments: args })).content[0].text);
  const format = (args = {}) => client.callTool({ name: 'format_diagnostic_report', arguments: args });
  const read = async uri => (await client.readResource({ uri })).contents[0];
  return { client, commands, report, format, read };
}

test('English: every section, the freeze frame apart from live data, and no VIN', async t => {
  const { report } = await session(t);
  const text = renderReport(await report(), 'en');
  assert.match(text, /^# Vehicle diagnostic report\n/);
  assert.match(text, /> \*\*Simulated data\.\*\* No real car was connected/);
  assert.match(text, /Collected \d{4}-\d{2}-\d{2} \d{2}:\d{2} UTC \(report 1 of this session\)/);
  assert.match(text, /- Check-engine light \(MIL\): \*\*on\*\*/);
  assert.match(text, /- Stored codes: P0420 \(SAE\)/);
  assert.match(text, /- Pending codes \(detected once, not confirmed\): none/);
  assert.match(text, /- Permanent codes \(stay until the car confirms a repair\): P0420 \(SAE\)/);
  assert.match(text, /- Code that stored it: P0420\n\n\| Reading \| Value \|\n\|---\|---\|\n\| Calculated engine load \| 34\.51% \|/);
  assert.match(text, /\| Engine RPM \| 2210 rpm \|/, 'freeze-frame rpm');
  assert.match(text, /\| Engine coolant temperature \| 88°C \|/);
  assert.ok(text.indexOf('## Freeze frame') < text.indexOf('## Live data'));
  assert.match(text, /- Incomplete: Evaporative system \(EVAP\)/);
  assert.match(text, /- Not supported by this car: Heated catalyst, Secondary air system, A\/C refrigerant/);
  assert.match(text, new RegExp(`Generated by obd2-mcp ${VERSION.replace(/\./g, '\\.')}\\.`));
  assert.doesNotMatch(text, /1HGFC2F59GA000042|VIN:|mock:catalyst|source/);
});

