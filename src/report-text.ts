const isObject = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null && !Array.isArray(v);

function section(report: Record<string, unknown>, name: string): { ok: true; data: Record<string, unknown> } | { ok: false; error: string | null } {
  const sections = isObject(report.sections) ? report.sections : {};
  const raw = sections[name];
  if (!isObject(raw) || !isObject(raw.data)) return { ok: false, error: null };
  if (raw.is_error === true) {
    const message = typeof raw.data.error === "string" ? raw.data.error.replace(/[\r\n|`<>]+/g, " ").replace(/\s+/g, " ").trim().slice(0, 300) : null;
    return { ok: false, error: message };
  }
  return { ok: true, data: raw.data };
}

function formatTime(value: unknown): string | null {
  const match = typeof value === "string" ? ISO_TIME.exec(value) : null;
  return match ? `${match[1]} ${match[2]} UTC` : null;
}

function unit(u: string): string {
  return u === "degC" ? "°C" : u === "degF" ? "°F" : u === "count" || u === "lambda" ? "" : u;
}

function value(v: number, u: string, system: UnitSystem): string {
  const converted = displayValue(v, u, system);
  const text = String(converted.value);
  const shown = unit(converted.unit);
  return shown ? (shown === "%" || shown === "°C" || shown === "°F" ? `${text}${shown}` : `${text} ${shown}`) : text;
}

export function renderReport(report: Record<string, unknown>, lang: ReportLanguage = "en", system: UnitSystem = "metric"): string {
  const t = T[lang];
  const lines: string[] = [`# ${t.title}`, ""];
  if (report.simulated === true) lines.push(t.simulated, "");
  const number = typeof report.session_report_number === "number" ? report.session_report_number : undefined;
  lines.push(t.collected(formatTime(report.started_at) ?? t.unavailable, number), "", t.disclaimer, "");

  const failure = (s: { ok: false; error: string | null }) => `${t.unavailable}${s.error ? (lang === "ja" ? `（${s.error}）` : ` (${s.error})`) : ""}`;
  const sep = lang === "ja" ? "：" : ": ";

  // Codes
  lines.push(`## ${t.codesHeading}`, "");
  const dtcs = section(report, "read_dtcs");
  const info = (data: Record<string, unknown>) => (isObject(data.code_info) ? data.code_info : {});
  const codes = (list: unknown, data: Record<string, unknown>): string => {
    if (!Array.isArray(list)) return t.noAnswer;
    const valid = list.filter((c): c is string => typeof c === "string" && CODE.test(c));
    if (valid.length !== list.length) return t.unavailable;
    if (valid.length === 0) return t.none;
    return valid
      .map(c => {
        const entry = info(data)[c];
        const definition = isObject(entry) && typeof entry.definition === "string" ? t.definedBy[entry.definition] : undefined;
        return definition ? (lang === "ja" ? `${c}（${definition}）` : `${c} (${definition})`) : c;
      })
      .join(lang === "ja" ? "、" : ", ");
  };
  const readiness = section(report, "read_readiness");
  const mil = dtcs.ok && typeof dtcs.data.mil_on === "boolean" ? dtcs.data.mil_on : readiness.ok && typeof readiness.data.mil_on === "boolean" ? readiness.data.mil_on : null;
  lines.push(`- ${t.mil}${sep}${mil === null ? t.unavailable : mil ? `**${t.on}**` : t.off}`);
  lines.push(`- ${t.stored}${sep}${dtcs.ok ? codes(dtcs.data.stored_dtcs, dtcs.data) : failure(dtcs)}`);
  lines.push(`- ${t.pending}${sep}${dtcs.ok ? codes(dtcs.data.pending_dtcs, dtcs.data) : failure(dtcs)}`);
  const permanent = section(report, "read_permanent_dtcs");
  if (permanent.ok || permanent.error !== null) {
    lines.push(`- ${t.permanent}${sep}${permanent.ok ? codes(permanent.data.permanent_dtcs, permanent.data) : failure(permanent)}`);
  }
  lines.push("");

  // Freeze frame
  lines.push(`## ${t.freezeHeading}`, "");
  const freeze = section(report, "read_freeze_frame");
  if (!freeze.ok) {
    lines.push(failure(freeze));
  } else if (freeze.data.freeze_frame === null || !isObject(freeze.data.freeze_frame)) {
    const note = typeof freeze.data.note === "string" ? freeze.data.note : "";
    lines.push(/^No freeze frame stored/.test(note) ? t.freezeNone : t.freezeUnknown);
  } else {
    const frame = freeze.data.freeze_frame;
    const code = typeof frame.dtc === "string" && CODE.test(frame.dtc) ? frame.dtc : t.unavailable;
    lines.push(`- ${t.freezeCode}${sep}${code}`, "");
    lines.push(...table(isObject(frame.conditions) ? frame.conditions : {}, lang, system));
  }
  lines.push("");

  // Live data
  lines.push(`## ${t.liveHeading}`, "");
  const live = section(report, "read_live_data");
  if (!live.ok) lines.push(failure(live));
  else lines.push(...table(isObject(live.data.live_data) ? live.data.live_data : {}, lang, system));
  lines.push("");

  // Readiness
  lines.push(`## ${t.readinessHeading}`, "");
  if (!readiness.ok) {
    lines.push(failure(readiness));
  } else {
    const monitors = isObject(readiness.data.readiness_monitors) ? readiness.data.readiness_monitors : {};
    const by = (state: string) => Object.keys(MONITORS).filter(name => monitors[name] === state).map(name => MONITORS[name][lang]);
    const row = (label: string, names: string[]) => `- ${label}${sep}${names.length ? names.join(lang === "ja" ? "、" : ", ") : t.none}`;
    lines.push(row(t.incomplete, by("incomplete")), row(t.complete, by("complete")), row(t.notSupported, by("not_supported")));
    const cycle = isObject(readiness.data.this_drive_cycle) ? readiness.data.this_drive_cycle : null;
    if (cycle && typeof cycle.complete_count === "number" && typeof cycle.enabled_count === "number" && isObject(cycle.monitors)) {
      const cycleMonitors = cycle.monitors;
      const running = Object.keys(MONITORS).filter(name => cycleMonitors[name] === "incomplete").map(name => MONITORS[name][lang]);
      const list = running.join(lang === "ja" ? "、" : ", ");
      const detail = !running.length ? "" : lang === "ja" ? `（${t.thisCycleIncomplete}：${list}）` : ` (${t.thisCycleIncomplete}: ${list})`;
      lines.push(`- ${t.thisCycle(cycle.complete_count, cycle.enabled_count)}${detail}`);
    }
  }
  lines.push("", "---", "", t.footer(VERSION), "");
  return lines.join("\n");
}

function table(readings: Record<string, unknown>, lang: ReportLanguage, system: UnitSystem): string[] {
  const t = T[lang];
  const rows: string[] = [`| ${t.sensor} | ${t.value} |`, "|---|---|"];
  for (const [name, entry] of Object.entries(readings)) {
    const def = PID_BY_NAME.get(name);
    if (!def) continue;
    const label = lang === "ja" ? SENSORS_JA[name] ?? def.desc : def.desc;
    const shown = isObject(entry) && typeof entry.value === "number" && Number.isFinite(entry.value) ? value(entry.value, def.unit, system) : t.failed;
    rows.push(`| ${label} | ${shown} |`);
  }
  return rows.length > 2 ? rows : [t.none];
}

/** "日本語", "Japanese", "ja" and similar → ja; anything else → en. */
export function reportLanguage(language: string | undefined): ReportLanguage {
  return language && /^(ja|jp|japanese|日本語|にほんご)/i.test(language.trim()) ? "ja" : "en";
}
